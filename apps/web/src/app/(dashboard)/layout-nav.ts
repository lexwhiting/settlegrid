/**
 * Decide which bottom-nav items to show based on the developer's
 * Stripe Connect status. Pure function — null and 'active' both
 * hide the onboarding link; any other value (e.g. 'not_started',
 * 'pending', 'restricted') surfaces it.
 */
export function buildBottomNavItems(status: string | null): BottomNavItem[] {
  const showOnboardingNav = status !== null && status !== 'active'
  return showOnboardingNav
    ? [ONBOARDING_NAV_ITEM, ...baseBottomNavItems]
    : baseBottomNavItems
}
